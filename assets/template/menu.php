<script>

        // Evitar doble click en menú pcoded
    $(".pcoded-hasmenu > a").on("dblclick", function(e) {
        e.preventDefault();
        e.stopPropagation();
    });

    // Arreglar comportamiento del toggle
    $(".pcoded-hasmenu > a").on("click", function(e) {
        e.preventDefault();

        let parent = $(this).closest("li");

        // Cerrar otros
        $(".pcoded-hasmenu").not(parent).removeClass("pcoded-trigger");

        // Toggle correcto
        parent.toggleClass("pcoded-trigger");
    });

</script>